-- the people a new ticket goes to: admins and the staff of its site (not deactivated)
create or replace function waytara._support_pool(p_ticket uuid)
returns table (staff_id uuid)
language sql
stable
security definer
set search_path = waytara, pg_temp
as $$
  select p.id
  from waytara.profiles p
  where p.deactivated_at is null and p.deleted_at is null
    and p.role::text in ('admin', 'employee', 'site_engineer')
    and waytara.support_staff_can_access_as(p.id, p_ticket)
$$;

create or replace function waytara._support_enqueue(p_ticket uuid, p_recipient uuid, p_audience text, p_kind text, p_payload jsonb, p_dedupe text, p_delay interval default interval '0 seconds')
returns void
language sql
security definer
set search_path = waytara, pg_temp
as $$
  insert into waytara.support_notifications (ticket_id, recipient_id, audience, kind, payload, dedupe_key, due_at)
  values (p_ticket, p_recipient, p_audience, p_kind, coalesce(p_payload, '{}'::jsonb), p_dedupe, now() + p_delay)
  on conflict (dedupe_key) do nothing
$$;

-- who hears about something the customer did: the person handling the ticket, or the whole pool while nobody is
create or replace function waytara._support_enqueue_staff(p_ticket uuid, p_kind text, p_payload jsonb, p_key text, p_delay interval default interval '0 seconds')
returns void
language plpgsql
security definer
set search_path = waytara, pg_temp
as $$
declare
  v_assignee uuid;
  r record;
begin
  select assigned_to into v_assignee from waytara.support_tickets where id = p_ticket;
  if v_assignee is not null then
    perform waytara._support_enqueue(p_ticket, v_assignee, 'staff', p_kind, p_payload, p_key || ':' || v_assignee, p_delay);
  else
    for r in select staff_id from waytara._support_pool(p_ticket) loop
      perform waytara._support_enqueue(p_ticket, r.staff_id, 'staff', p_kind, p_payload, p_key || ':' || r.staff_id, p_delay);
    end loop;
  end if;
end;
$$;

-- a new row due now asks the dashboard app's mailer to run (the same way fleet_tick does); the once-a-minute job below is the safety net
create or replace function waytara._support_kick()
returns trigger
language plpgsql
security definer
set search_path = waytara, pg_temp
as $$
begin
  if exists (select 1 from new_rows where due_at <= now() + interval '2 seconds') then
    perform waytara.invoke_cron_route('/api/cron/send-support-notifications');
  end if;
  return null;
end;
$$;

drop trigger if exists support_notifications_kick on waytara.support_notifications;
create trigger support_notifications_kick after insert on waytara.support_notifications
  referencing new table as new_rows
  for each statement execute function waytara._support_kick();

