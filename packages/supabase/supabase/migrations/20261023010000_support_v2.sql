-- hand a ticket to someone (or to nobody): the thread line, and the e-mails to the customer, the new person and the one who had it
create or replace function waytara._support_assign(p_ticket uuid, p_to uuid, p_actor uuid, p_notify boolean default true)
returns void
language plpgsql
security definer
set search_path = waytara, pg_temp
as $$
declare
  t waytara.support_tickets;
  v_actor_name text := waytara._support_name(p_actor);
  v_to_name text;
  v_to_role text;
  v_prev uuid;
  v_prev_name text;
  v_event text;
  v_text text;
  v_msg uuid;
  v_payload jsonb;
begin
  select * into t from waytara.support_tickets where id = p_ticket for update;
  if not found then raise exception 'No such ticket' using errcode = 'P0002'; end if;
  v_prev := t.assigned_to;
  v_prev_name := t.assigned_name;

  if p_to is null then
    if v_prev is null then return; end if;
    update waytara.support_tickets
       set assigned_to = null, assigned_name = null, assigned_role = null, assigned_at = null,
           status = case when status = 'in_progress' then 'open' else status end, updated_at = now()
     where id = p_ticket;
    perform waytara._support_event(p_ticket, 'released', v_actor_name || ' released this ticket back to the team');
    return;
  end if;

  if not waytara.support_staff_can_access_as(p_to, p_ticket) then
    raise exception 'That person cannot work on this ticket' using errcode = '22023';
  end if;
  if v_prev = p_to then return; end if;

  select waytara._support_name(p_to), role::text into v_to_name, v_to_role from waytara.profiles where id = p_to;
  update waytara.support_tickets
     set assigned_to = p_to, assigned_name = v_to_name, assigned_role = v_to_role, assigned_at = now(),
         status = case when status = 'open' then 'in_progress' else status end, updated_at = now()
   where id = p_ticket;

  if p_actor = p_to then
    v_event := case when v_prev is null then 'taken' else 'reassigned' end;
    v_text := case when v_prev is null then v_to_name || ' took this ticket' else v_to_name || ' took this ticket over from ' || coalesce(v_prev_name, 'someone') end;
  elsif v_prev is null then
    v_event := 'assigned';
    v_text := v_actor_name || ' assigned this ticket to ' || v_to_name;
  else
    v_event := 'reassigned';
    v_text := v_actor_name || ' reassigned this ticket from ' || coalesce(v_prev_name, 'someone') || ' to ' || v_to_name;
  end if;
  v_msg := waytara._support_event(p_ticket, v_event, v_text);

  if p_notify then
    v_payload := jsonb_build_object('ticket_no', t.ticket_no, 'subject', t.subject, 'actor_name', v_actor_name, 'assignee_name', v_to_name, 'assignee_role', v_to_role,
                                    'previous_name', v_prev_name, 'self', p_actor = p_to);
    perform waytara._support_enqueue(p_ticket, t.customer_id, 'customer', case when v_prev is null then 'taken' else 'reassigned' end, v_payload, 'assign:' || v_msg || ':' || t.customer_id);
    if p_actor <> p_to then
      perform waytara._support_enqueue(p_ticket, p_to, 'staff', 'assigned_to_you', v_payload, 'assign:' || v_msg || ':' || p_to);
    end if;
    if v_prev is not null and v_prev <> p_actor and v_prev <> p_to then
      perform waytara._support_enqueue(p_ticket, v_prev, 'staff', 'unassigned_from_you', v_payload, 'assign:' || v_msg || ':' || v_prev);
    end if;
  end if;
end;
$$;

