-- Support v2: a ticket belongs to a site and goes to a pool (the site's installer, the site's employees and the admins); anyone in the pool
-- can take it or hand it to another person; the customer is told of every step by e-mail; messages carry several attachments, "seen"
-- marks and staff-only notes; a ticket is resolved or closed with a rating.
--
-- Every change to a ticket goes through the functions below (SECURITY DEFINER, signed-in people only). The tables can only be READ by the
-- people who may see the ticket: nobody writes them directly, so a customer cannot assign a ticket to somebody or set their own rating.
-- E-mails are queued in support_notifications and sent by the dashboard app's mailer (one row per event: sending twice is impossible).
-- To undo: see the bottom.

