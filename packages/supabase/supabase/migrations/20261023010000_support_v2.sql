-- "I have read this": the customer's side or the staff's side of the ticket (this is what makes the "seen" marks)
create or replace function waytara.support_mark_read(p_ticket uuid)
returns void
language plpgsql
security definer
set search_path = waytara, pg_temp
as $$
declare
  v_me uuid := (select auth.uid());
  t waytara.support_tickets;
begin
  select * into t from waytara.support_tickets where id = p_ticket;
  if not found then return; end if;
  if t.customer_id = v_me then
    if t.unread_customer > 0 or t.customer_last_read_at is null or t.customer_last_read_at < coalesce(t.last_message_at, t.created_at) then
      update waytara.support_tickets set customer_last_read_at = now(), unread_customer = 0 where id = p_ticket;
    end if;
  elsif waytara.support_staff_can_access_as(v_me, p_ticket) then
    if t.unread_staff > 0 or t.staff_last_read_at is null or t.staff_last_read_at < coalesce(t.last_message_at, t.created_at) then
      update waytara.support_tickets set staff_last_read_at = now(), staff_last_read_name = waytara._support_name(v_me), unread_staff = 0 where id = p_ticket;
    end if;
  end if;
end;
$$;

-- who a ticket can be given to: the admins and the staff of its site, with how many open tickets each has now
create or replace function waytara.support_assignees(p_ticket uuid)
returns table (id uuid, full_name text, role text, is_you boolean, open_tickets integer)
language plpgsql
stable
security definer
set search_path = waytara, pg_temp
as $$
declare
  v_me uuid := (select auth.uid());
begin
  if v_me is null or not waytara.support_staff_can_access_as(v_me, p_ticket) then return; end if;
  return query
    select p.id, waytara._support_name(p.id), p.role::text, p.id = v_me,
           (select count(*)::int from waytara.support_tickets x where x.assigned_to = p.id and x.status in ('open', 'in_progress'))
    from waytara.profiles p
    where p.deactivated_at is null and p.deleted_at is null and p.role::text in ('admin', 'employee', 'site_engineer')
      and waytara.support_staff_can_access_as(p.id, p_ticket)
    order by (p.role::text = 'admin'), waytara._support_name(p.id);
end;
$$;

