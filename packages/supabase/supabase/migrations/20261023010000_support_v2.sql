-- Staff who may work a ticket: an admin; an employee or site engineer assigned to the ticket's site (site_staff) or, for a ticket with no site,
-- the employee the customer was onboarded by. A deactivated or deleted account is nobody.
create or replace function waytara.support_staff_can_access_as(p_user uuid, p_ticket uuid)
returns boolean
language sql
stable
security definer
set search_path = waytara, pg_temp
as $$
  select p_user is not null and exists (
    select 1
    from waytara.support_tickets t
    join waytara.profiles me on me.id = p_user
    where t.id = p_ticket
      and me.deactivated_at is null and me.deleted_at is null
      and (
        me.role::text = 'admin'
        or (
          me.role::text in ('employee', 'site_engineer')
          and (
            (t.site_id is not null and exists (
              select 1 from waytara.site_staff ss
              where ss.site_id = t.site_id and ss.staff_id = p_user and ss.removed_at is null and (ss.expires_at is null or ss.expires_at > now())
            ))
            or exists (select 1 from waytara.customer_onboarding co where co.customer_id = t.customer_id and co.employee_id = p_user)
          )
        )
      )
  )
$$;

create or replace function waytara.support_staff_can_access(p_ticket uuid)
returns boolean
language sql
stable
security definer
set search_path = waytara, pg_temp
as $$
  select waytara.support_staff_can_access_as((select auth.uid()), p_ticket)
$$;

-- the customer of the ticket, or staff who may work it (used by the storage rules too)
create or replace function waytara.support_can_access_as(p_user uuid, p_ticket uuid)
returns boolean
language sql
stable
security definer
set search_path = waytara, pg_temp
as $$
  select p_user is not null and (
    exists (select 1 from waytara.support_tickets t join waytara.profiles me on me.id = p_user
            where t.id = p_ticket and t.customer_id = p_user and me.deactivated_at is null and me.deleted_at is null)
    or waytara.support_staff_can_access_as(p_user, p_ticket)
  )
$$;

-- the ticket an uploaded file belongs to: the first folder of its path (a ticket id), or null when it is not one
create or replace function waytara.support_object_ticket(p_name text)
returns uuid
language sql
immutable
set search_path = waytara, pg_temp
as $$
  select case when split_part(p_name, '/', 1) ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then split_part(p_name, '/', 1)::uuid end
$$;

