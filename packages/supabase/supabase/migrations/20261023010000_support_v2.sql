-- staff change the status: open, in_progress, resolved or closed
create or replace function waytara.support_set_status(p_ticket uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = waytara, pg_temp
as $$
declare
  v_me uuid := (select auth.uid());
  v_name text;
  t waytara.support_tickets;
  v_msg uuid;
  v_payload jsonb;
begin
  if v_me is null or not waytara.support_staff_can_access_as(v_me, p_ticket) then raise exception 'You cannot work on this ticket' using errcode = '42501'; end if;
  if p_status not in ('open', 'in_progress', 'resolved', 'closed') then raise exception 'Unknown status' using errcode = '22023'; end if;
  v_name := waytara._support_name(v_me);
  select * into t from waytara.support_tickets where id = p_ticket for update;
  if t.status = p_status then return; end if;

  -- whoever resolves or closes a ticket nobody had is the one who handled it
  if t.assigned_to is null and p_status in ('in_progress', 'resolved', 'closed') then
    perform waytara._support_assign(p_ticket, v_me, v_me, false);
  end if;

  v_payload := jsonb_build_object('ticket_no', t.ticket_no, 'subject', t.subject, 'actor_name', v_name, 'assignee_name', coalesce((select assigned_name from waytara.support_tickets where id = p_ticket), v_name));
  if p_status = 'resolved' then
    update waytara.support_tickets set status = 'resolved', resolved_at = now(), closed_at = null, closed_by = null, updated_at = now() where id = p_ticket;
    v_msg := waytara._support_event(p_ticket, 'resolved', v_name || ' marked this ticket as resolved');
    perform waytara._support_enqueue(p_ticket, t.customer_id, 'customer', 'resolved', v_payload, 'status:' || v_msg || ':' || t.customer_id);
  elsif p_status = 'closed' then
    update waytara.support_tickets set status = 'closed', closed_at = now(), closed_by = 'staff', resolved_at = coalesce(resolved_at, now()), updated_at = now() where id = p_ticket;
    v_msg := waytara._support_event(p_ticket, 'closed', v_name || ' closed this ticket');
    perform waytara._support_enqueue(p_ticket, t.customer_id, 'customer', 'closed', v_payload, 'status:' || v_msg || ':' || t.customer_id);
  else
    update waytara.support_tickets set status = p_status, resolved_at = null, closed_at = null, closed_by = null, updated_at = now() where id = p_ticket;
    if t.status in ('resolved', 'closed') then
      v_msg := waytara._support_event(p_ticket, 'reopened', v_name || ' reopened this ticket');
      perform waytara._support_enqueue(p_ticket, t.customer_id, 'customer', 'reopened', v_payload, 'status:' || v_msg || ':' || t.customer_id);
    end if;
  end if;
end;
$$;

-- the customer closes the ticket, with a rating if they like
create or replace function waytara.support_customer_close(p_ticket uuid, p_rating smallint default null, p_comment text default null)
returns void
language plpgsql
security definer
set search_path = waytara, pg_temp
as $$
declare
  v_me uuid := (select auth.uid());
  v_name text;
  t waytara.support_tickets;
  v_msg uuid;
  v_comment text := nullif(left(btrim(coalesce(p_comment, '')), 1000), '');
  v_payload jsonb;
begin
  select * into t from waytara.support_tickets where id = p_ticket for update;
  if not found or t.customer_id is distinct from v_me then raise exception 'No such ticket' using errcode = 'P0002'; end if;
  if p_rating is not null and p_rating not between 1 and 5 then raise exception 'A rating is 1 to 5' using errcode = '22023'; end if;
  if t.status = 'closed' then return; end if;
  v_name := waytara._support_name(v_me);

  update waytara.support_tickets
     set status = 'closed', closed_at = now(), closed_by = 'customer', resolved_at = coalesce(resolved_at, now()), updated_at = now(),
         rating = coalesce(p_rating, rating), rating_comment = case when p_rating is not null then v_comment else rating_comment end,
         rated_at = case when p_rating is not null then now() else rated_at end
   where id = p_ticket;
  v_msg := waytara._support_event(p_ticket, 'closed', v_name || ' closed this ticket' || case when p_rating is not null then ' and rated it ' || p_rating || ' out of 5' else '' end);
  v_payload := jsonb_build_object('ticket_no', t.ticket_no, 'subject', t.subject, 'actor_name', v_name, 'rating', p_rating, 'comment', v_comment);
  perform waytara._support_enqueue_staff(p_ticket, 'closed_by_customer', v_payload, 'close:' || v_msg);
end;
$$;

